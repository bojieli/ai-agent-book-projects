def compile_replacements(mapping: dict[str, str], words: bool) -> list[tuple[re.Pattern[str], str]]:
    ordered = sorted(mapping.items(), key=lambda item: len(item[0]), reverse=True)
    compiled = []
    for source, target in ordered:
        # A handful of useful exact phrase mappings are single English words
        # (for example, "ratio" and "format").  Treating those as arbitrary
        # substrings corrupts longer labels such as "generation" and
        # "information", so ASCII word-like entries always get boundaries.
        if words or re.fullmatch(r"[A-Za-z0-9_-]+", source):
            pattern = rf"(?<![\w/]){re.escape(source)}(?![\w/])"
        else:
            pattern = re.escape(source)
        compiled.append((re.compile(pattern, re.IGNORECASE), target))
    return compiled


PHRASE_PATTERNS = compile_replacements(PHRASES, words=False)
MONO_PHRASE_PATTERNS = compile_replacements(
    {
        source: target
        for source, target in PHRASES.items()
        if any(character.isspace() for character in source)
        or source in {
            "assistant：tool_search_call(github)",
            "reviewer→proposer",
        }
        or re.search(r"[一-鿿]", source)
    },
    words=False,
)
WORD_PATTERNS = compile_replacements(WORDS, words=True)


def replace_all(text: str, patterns: list[tuple[re.Pattern[str], str]]) -> str:
    for pattern, target in patterns:
        text = pattern.sub(target, text)
    return text


def translate_fragment(fragment: str, monospace: bool) -> tuple[str, bool]:
    decoded = html.unescape(fragment)
    # Code, JSON, protocol tags, shell commands, and formulas retain their
    # identifiers. Explicit phrase mappings above may still localize natural
    # prose embedded in a code example.
    code_like = (
        monospace
        or decoded.lstrip().startswith(("<", "{", "}", "$", "#!"))
        or "<|" in decoded
        or re.search(r"\b(?:def|return|import|SELECT|FROM|GROUP BY)\b", decoded)
        or re.search(r"\b[a-z][a-z0-9]*_[a-z0-9_]+\s*\(", decoded)
        or re.search(r"\b[a-z][a-z0-9_-]*(?:\.[a-z][a-z0-9_-]*)+\b", decoded, re.I)
    )
    translated = replace_all(
        decoded,
        MONO_PHRASE_PATTERNS if code_like else PHRASE_PATTERNS,
    )
    if not code_like:
        translated = replace_all(translated, WORD_PATTERNS)

    return html.escape(translated, quote=False), translated != decoded


def localize_svg(source: str) -> tuple[str, int, int]:
    translated_nodes = 0
    total_nodes = 0

    def localize_text(match: re.Match[str]) -> str:
        nonlocal translated_nodes, total_nodes
        attrs = match.group("attrs")
        body = match.group("body")
        monospace = "Courier" in attrs or "monospace" in attrs

        parts = re.split(r"(<[^>]+>)", body)
        changed = False
        for index, part in enumerate(parts):
            if not part or part.startswith("<"):
                continue
            total_nodes += 1
            parts[index], part_changed = translate_fragment(part, monospace)
            changed = changed or part_changed
        if changed:
            translated_nodes += 1
        return match.group(1) + "".join(parts) + match.group(4)

    return TEXT_RE.sub(localize_text, source), translated_nodes, total_nodes


def write_localized_svg(src: Path, dst: Path) -> None:
    shutil.copy2(src, dst)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--keep-svg",
        action="store_true",
        help="also retain localized SVG sources in book-hu/images-svg",
    )
    args = parser.parse_args()

    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    subprocess.run(
        [sys.executable, str(ROOT / "book-hu" / "gen_ch2_figs.py")],
        check=True,
    )

    # Chapter 2 has a dedicated Chinese-golden SVG workflow. Excluding it here
    # prevents the obsolete English numbering from recreating stale PNGs.
    svg_sources = sorted(
        path for path in SOURCE_DIR.glob("*.svg")
        if not CHAPTER2_STEM_RE.fullmatch(path.stem)
    )
    png_sources = sorted(
        path for path in SOURCE_DIR.glob("*.png")
        if not CHAPTER2_STEM_RE.fullmatch(path.stem)
    )
    png_stems = {path.stem for path in png_sources}

    translated_text_nodes = 0
    total_text_nodes = 0
    written = 0

    with tempfile.TemporaryDirectory(prefix="ai-agent-book-hu-figures.") as temp:
        temp_dir = Path(temp)
        localized_svgs: list[Path] = []

        for source_path in svg_sources:
            # When both source formats exist, the raster source takes precedence.
            if source_path.stem in png_stems:
                continue
            localized, translated, total = localize_svg(
                source_path.read_text(encoding="utf-8")
            )
            for old, new in SVG_LAYOUT_FIXUPS.get(source_path.name, ()):
                localized = localized.replace(old, new)
            output_path = temp_dir / source_path.name
            output_path.write_text(localized, encoding="utf-8")
            localized_svgs.append(output_path)
            translated_text_nodes += translated
            total_text_nodes += total

        # Reuse the edition's established overflow fitter after Hungarian text
        # expansion, then copy the localized SVGs into book-hu/images/.
        subprocess.run(
            ["python3", str(FIT_SCRIPT), *map(str, localized_svgs)],
            check=True,
            stdout=subprocess.DEVNULL,
        )

        for svg_path in localized_svgs:
            write_localized_svg(svg_path, OUTPUT_DIR / svg_path.name)
            written += 1

        if args.keep_svg:
            svg_output = ROOT / "book-hu" / "images-svg"
            if svg_output.exists():
                shutil.rmtree(svg_output)
            shutil.copytree(temp_dir, svg_output)

    for source_path in png_sources:
        shutil.copy2(source_path, OUTPUT_DIR / source_path.name)

    expected = (
        {path.name for path in svg_sources if path.stem not in png_stems}
        | {path.name for path in png_sources}
        | {f"fig2-{figure}.svg" for figure in range(1, 18)}
    )
    actual = {
        path.name
        for pattern in ("*.svg", "*.png")
        for path in OUTPUT_DIR.glob(pattern)
    }
    missing = sorted(expected - actual)
    extra = sorted(actual - expected)
    if missing or extra:
        raise SystemExit(f"Image inventory mismatch; missing={missing}, extra={extra}")

    print(
        "Generated 17 Chapter 2 SVGs; "
        f"localized {translated_text_nodes}/{total_text_nodes} other SVG text nodes; "
        f"wrote {written} other localized SVG diagrams and copied "
        f"{len(png_sources)} PNG sources."
    )


if __name__ == "__main__":
    main()
